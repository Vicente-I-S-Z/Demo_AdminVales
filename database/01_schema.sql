-- 1. EXTENSIONES NECESARIAS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- 2. TABLA: authorized_emails (Lista blanca de correos autorizados y empresa)
CREATE TABLE IF NOT EXISTS authorized_emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    empresa TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_authorized_emails_email ON authorized_emails (email);

-- 3. TABLA: user_profiles (Perfiles de usuario, roles y estado de vales)
CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nombre TEXT,
    apellidos TEXT,
    empresa TEXT,
    rol TEXT NOT NULL DEFAULT 'usuario' CHECK (rol IN ('usuario', 'admin', 'lider')),
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    vales_disabled_from DATE,
    vales_disabled_to DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_user_profiles_email ON user_profiles (email);
CREATE INDEX IF NOT EXISTS idx_user_profiles_rol ON user_profiles (rol);

-- 4. TABLA: lideres (Nómina de supervisores / líderes de equipo)
CREATE TABLE IF NOT EXISTS lideres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lider TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    email TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_lideres_numero ON lideres (numero_lider);

-- 5. TABLA: calendar_blocks (Bloqueos de vales programados por fechas)
CREATE TABLE IF NOT EXISTS calendar_blocks (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_email TEXT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_termino DATE NOT NULL,
    descripcion TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_calendar_blocks_email ON calendar_blocks (user_email);
CREATE INDEX IF NOT EXISTS idx_calendar_blocks_fechas ON calendar_blocks (fecha_inicio, fecha_termino);

-- 6. TABLA: daily_user_codes (Códigos de colación diarios generados)
CREATE TABLE IF NOT EXISTS daily_user_codes (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_email TEXT,
    auth_user_id TEXT,
    codigo_diario TEXT NOT NULL UNIQUE,
    fecha_generacion DATE NOT NULL DEFAULT CURRENT_DATE,
    hora_generacion TIMESTAMPTZ DEFAULT NOW(),
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_uso TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    qr_data TEXT,
    user_name TEXT,
    empresa TEXT,
    nombre_invitado TEXT,
    apellido_invitado TEXT
);
CREATE INDEX IF NOT EXISTS idx_daily_user_codes_code ON daily_user_codes (codigo_diario);
CREATE INDEX IF NOT EXISTS idx_daily_user_codes_email ON daily_user_codes (user_email);
CREATE INDEX IF NOT EXISTS idx_daily_user_codes_fecha ON daily_user_codes (fecha_generacion);

-- 7. TABLA: code_authorizations (Autorizaciones diferidas de vales)
CREATE TABLE IF NOT EXISTS code_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_diario TEXT NOT NULL UNIQUE,
    is_authorized BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_code_auth_code ON code_authorizations (codigo_diario);

-- 8. TABLA: qr_registrations (Validaciones/canjes de códigos en restaurantes)
CREATE TABLE IF NOT EXISTS qr_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_code TEXT NOT NULL,
    date DATE NOT NULL,
    time TEXT NOT NULL,
    restaurante TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_qr_registrations_code ON qr_registrations (qr_code);
CREATE INDEX IF NOT EXISTS idx_qr_registrations_date ON qr_registrations (date);
CREATE INDEX IF NOT EXISTS idx_qr_registrations_rest ON qr_registrations (restaurante);

-- 9. TABLA: solicitudes_desbloqueo (Peticiones de supervisores a administradores)
CREATE TABLE IF NOT EXISTS solicitudes_desbloqueo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lider TEXT NOT NULL,
    user_email TEXT NOT NULL,
    justificacion TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_solicitudes_email ON solicitudes_desbloqueo (user_email);

-- 10. TABLA: vales_contingencia_manual (Vales físicos/manuales por contingencia)
CREATE TABLE IF NOT EXISTS vales_contingencia_manual (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    nombre_trabajador TEXT NOT NULL,
    empresa TEXT NOT NULL,
    restaurante TEXT NOT NULL,
    fecha_consumo DATE NOT NULL,
    notas TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_vales_cont_fecha ON vales_contingencia_manual (fecha_consumo);

-- 11. TABLA: support_tickets (Mesa de ayuda y gestión de incidencias TI)
CREATE TABLE IF NOT EXISTS support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code TEXT NOT NULL UNIQUE,
    sistema_origen TEXT NOT NULL DEFAULT 'vales_admin',
    titulo TEXT NOT NULL,
    descripcion TEXT NOT NULL,
    categoria TEXT NOT NULL,
    prioridad TEXT NOT NULL DEFAULT 'media',
    estado TEXT NOT NULL DEFAULT 'abierto',
    reportado_por TEXT NOT NULL,
    reportado_por_nombre TEXT,
    solucion TEXT,
    resuelto_por TEXT,
    fecha_resolucion TIMESTAMPTZ,
    contexto_operativo JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_support_tickets_code ON support_tickets (ticket_code);
CREATE INDEX IF NOT EXISTS idx_support_tickets_reportado ON support_tickets (reportado_por);

-- 12. FUNCIÓN RPC: Desbloqueo automático de vales por expiración de calendario
CREATE OR REPLACE FUNCTION update_user_status_by_calendar_blocks()
RETURNS jsonb AS $$
DECLARE
    v_today DATE := CURRENT_DATE;
    v_disabled_count INTEGER := 0;
    v_enabled_count INTEGER := 0;
    v_cleaned_dates INTEGER := 0;
BEGIN
    -- Deshabilitar usuarios con bloqueo activo hoy
    UPDATE user_profiles
    SET habilitado = false
    WHERE email IN (
        SELECT DISTINCT user_email
        FROM calendar_blocks
        WHERE user_email IS NOT NULL
        AND v_today BETWEEN fecha_inicio AND fecha_termino
    )
    AND (habilitado = true OR habilitado IS NULL);
    GET DIAGNOSTICS v_disabled_count = ROW_COUNT;

    -- Rehabilitar usuarios cuyos bloqueos ya expiraron
    UPDATE user_profiles up
    SET habilitado = true
    WHERE up.habilitado = false
    AND NOT EXISTS (
        SELECT 1
        FROM calendar_blocks cb
        WHERE cb.user_email = up.email
        AND v_today BETWEEN cb.fecha_inicio AND cb.fecha_termino
    )
    AND EXISTS (
        SELECT 1
        FROM calendar_blocks cb
        WHERE cb.user_email = up.email
        AND cb.fecha_termino < v_today
    );
    GET DIAGNOSTICS v_enabled_count = ROW_COUNT;

    -- Limpiar fechas temporales expiradas
    UPDATE user_profiles
    SET vales_disabled_from = NULL,
        vales_disabled_to = NULL,
        habilitado = true
    WHERE vales_disabled_to IS NOT NULL
    AND vales_disabled_to < v_today
    AND NOT EXISTS (
        SELECT 1
        FROM calendar_blocks cb
        WHERE cb.user_email = user_profiles.email
        AND v_today BETWEEN cb.fecha_inicio AND cb.fecha_termino
    );
    GET DIAGNOSTICS v_cleaned_dates = ROW_COUNT;

    RETURN jsonb_build_object(
        'deshabilitados_hoy', v_disabled_count,
        'habilitados_automaticamente', v_enabled_count,
        'fechas_limpiadas', v_cleaned_dates
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
